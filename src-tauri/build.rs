//! Embeds the patch's files (payload/, filled by scripts/sync-payload.ps1) into the launcher, so one
//! executable carries everything it installs. Without a payload the launcher still builds, for UI work, and says so.

use std::{env, fmt::Write as _, fs, path::PathBuf};

#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase")]
struct PayloadJson {
    decomp_version: String,
    decomp_commit: Option<String>,
    supported_sha256: String,
    retail_safe_disc_sha256: String,
    files: Vec<PayloadFileJson>,
}

#[derive(serde::Deserialize)]
struct PayloadFileJson {
    path: String,
    file: String,
    keep: bool,
    sha256: String,
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let payload_dir = manifest_dir.join("..").join("payload");
    let payload_json = payload_dir.join("payload.json");
    println!("cargo:rerun-if-changed={}", payload_json.display());

    let mut code = String::from("// Generated by build.rs from payload/payload.json.\n");
    match fs::read_to_string(&payload_json) {
        Ok(text) => {
            let payload: PayloadJson = serde_json::from_str(&text).expect("payload/payload.json is malformed");
            writeln!(code, "pub const DECOMP_VERSION: &str = {:?};", payload.decomp_version).unwrap();
            writeln!(code, "pub const DECOMP_COMMIT: &str = {:?};", payload.decomp_commit.unwrap_or_default()).unwrap();
            writeln!(code, "pub const SUPPORTED_SHA256: &str = {:?};", payload.supported_sha256).unwrap();
            writeln!(code, "pub const RETAIL_SAFEDISC_SHA256: &str = {:?};", payload.retail_safe_disc_sha256).unwrap();
            code.push_str("pub static FILES: &[PayloadFile] = &[\n");
            for file in &payload.files {
                let source = payload_dir.join(&file.file).canonicalize().unwrap_or_else(|_| {
                    panic!("payload file {} is missing: run scripts/sync-payload.ps1", file.file)
                });
                println!("cargo:rerun-if-changed={}", source.display());
                writeln!(
                    code,
                    "    PayloadFile {{ path: {:?}, keep: {}, sha256: {:?}, data: include_bytes!({:?}) }},",
                    file.path,
                    file.keep,
                    file.sha256,
                    source.display().to_string()
                )
                .unwrap();
            }
            code.push_str("];\n");
        }
        Err(_) => {
            println!("cargo:warning=payload/payload.json is missing: this launcher has no patch to install. Run scripts/sync-payload.ps1.");
            code.push_str(
                "pub const DECOMP_VERSION: &str = \"\";\npub const DECOMP_COMMIT: &str = \"\";\n\
                 pub const SUPPORTED_SHA256: &str = \"86a30b08ab2ea8a240403d37f8f0303cf65aa5cde8e7f673049ab01654ccf755\";\n\
                 pub const RETAIL_SAFEDISC_SHA256: &str = \"b1163b44f4e6c5e64d81d5fcce95dea8efdc587ad52910df4d4942e01dbfb3d1\";\n\
                 pub static FILES: &[PayloadFile] = &[];\n",
            );
        }
    }
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("payload.rs");
    fs::write(out, code).unwrap();

    tauri_build::build();
}
